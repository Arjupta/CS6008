#!/bin/bash
# Phase 4, Run B: the operator mistake -- domain-ns signs example.com
# exactly as normal (fully, correctly signed), but tld-ns's com zone is
# signed WITHOUT ever being given example.com's DS record. The child zone
# is genuinely, properly signed; the parent simply never published the one
# record that lets a validator find that out.
#
# This is a one-line difference from sign-zones.sh (Run A): step 2 below
# skips appending domain-ns's dsset-example.com. into tld-ns/build/db.com
# before signing com. Everything else -- domain-ns's signing, root's
# signing, the trust anchor derivation -- is identical, because the root
# -> com link is still fully intact; only the com -> example.com link is
# broken.
#
# Run from inside phase4/, before `docker compose up` (Run B). Re-running
# ./sign-zones.sh afterwards switches back to Run A's full chain.

set -e

IMG=cs6008-bindtools
ALG=ECDSAP256SHA256

echo "== Building signing-tool image =="
docker build -q -t "$IMG" -f ../common/Dockerfile.bind ../common >/dev/null

run_in() {
  local dir="$1"; shift
  docker run --rm -v "$(pwd)/$dir:/work" -w /work "$IMG" bash -c "$*"
}

echo "== Cleaning previous generated artifacts =="
for d in domain-ns tld-ns root-ns; do
  rm -rf "$d/keys" "$d/build" "$d"/*.signed
  mkdir -p "$d/keys" "$d/build"
done
rm -f resolver/trust-anchor.conf

# ---- 1. domain-ns signs example.com (leaf zone) -- unchanged, fully signed -
echo "== [1/4] Signing example.com (domain-ns) -- fully signed, as always =="
run_in domain-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys example.com. >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys example.com. >/dev/null
  cp db.example.com build/db.example.com
  cd build
  dnssec-signzone -S -N keep -K ../keys -o example.com. \
      -f db.example.com.signed db.example.com >/dev/null
"
cp domain-ns/build/db.example.com.signed domain-ns/db.example.com.signed

# ---- 2. tld-ns signs com -- THE OPERATOR MISTAKE: no DS for example.com ----
echo "== [2/4] Signing com (tld-ns) -- Run B: example.com's DS deliberately NOT published =="
cp tld-ns/db.com tld-ns/build/db.com
# (Run A appends domain-ns/build/dsset-example.com. here. Run B does not --
#  com. still delegates example.com. via its NS records, so resolution
#  still works, but nothing in com. vouches for example.com.'s key.)
run_in tld-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys com. >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys com. >/dev/null
  cd build
  dnssec-signzone -S -N keep -K ../keys -o com. \
      -f db.com.signed db.com >/dev/null
"
cp tld-ns/build/db.com.signed tld-ns/db.com.signed

# ---- 3. root-ns: chain in com's DS, then sign the root zone (unaffected) ---
echo "== [3/4] Chaining com's DS into the root zone, signing . (root-ns) =="
cp root-ns/db.root root-ns/build/db.root
{
  echo ""
  echo "; DS record for the com delegation (chains to its signed zone)"
  cat tld-ns/build/dsset-com.
} >> root-ns/build/db.root
run_in root-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys . >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys . >/dev/null
  cd build
  dnssec-signzone -S -N keep -K ../keys -o . \
      -f db.root.signed db.root >/dev/null
  mv 'dsset-.' dsset-root
"
cp root-ns/build/db.root.signed root-ns/db.root.signed

# ---- 4. derive the resolver's trust anchor from root-ns's own DS -----------
echo "== [4/4] Writing resolver trust anchor from root-ns's DS =="
DS_LINE=$(grep -E "IN[[:space:]]+DS" root-ns/build/dsset-root | head -1)
read -r KEYTAG DSALGO DIGTYPE DIGEST <<<"$(echo "$DS_LINE" | awk '
  { for (i=1;i<=NF;i++) if ($i=="DS") {
      d=""; for (j=i+4;j<=NF;j++) d=d $j
      print $(i+1), $(i+2), $(i+3), d
      exit
    } }')"

cat > resolver/trust-anchor.conf <<EOF
// Generated by sign-zones-runB.sh -- DO NOT COMMIT, see .gitignore.
trust-anchors {
    "." static-ds $KEYTAG $DSALGO $DIGTYPE "$DIGEST";
};
EOF

echo
echo "Done (Run B -- example.com signed, but com publishes NO DS for it)."
echo "  domain-ns/db.example.com.signed  (fully signed, same as Run A)"
echo "  tld-ns/db.com.signed             (NO DS for example.com -- the mistake)"
echo "  root-ns/db.root.signed           (root -> com link unaffected)"
echo "  resolver/trust-anchor.conf  ->  $(cat resolver/trust-anchor.conf | tail -2 | head -1)"
echo
echo "Now run: docker compose up -d --build"
