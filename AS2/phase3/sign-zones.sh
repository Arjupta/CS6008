#!/bin/bash
# Phase 3: generate DNSSEC keys and sign the zone hierarchy.
#
# Must run in dependency order, leaf -> root, because each parent zone needs
# its child's DS record (computed from the child's freshly-generated KSK)
# before the parent itself can be signed:
#   1. domain-ns signs example.com                     (no child to wait on)
#   2. tld-ns chains example.com's DS into com, signs com
#   3. root-ns chains com's DS into the root zone, signs .
#   4. the resolver's trust anchor is derived from root-ns's own DS
#
# Uses the same Dockerfile.bind image already used for root-ns/tld-ns/
# domain-ns/resolver (it already has bind9utils, i.e. dnssec-keygen and
# dnssec-signzone) as an ephemeral signing-tool container, so nothing needs
# installing on the host.
#
# Safe to re-run: wipes and regenerates every generated artifact each time.
# Keys, signed zones and the resolver's trust anchor are NOT committed to
# git (see .gitignore) -- this script is what the grader runs to produce
# them locally, every time, from the plain source zone files that ARE
# committed (db.root, db.com, db.example.com -- no DS records in them).
#
# Run from inside phase3/, before `docker compose up`.

set -e

IMG=cs6008-bindtools
ALG=ECDSAP256SHA256   # modern, compact signatures; see README for rationale

echo "== Building signing-tool image =="
docker build -q -t "$IMG" -f ../common/Dockerfile.bind ../common >/dev/null

run_in() {
  local dir="$1"; shift
  docker run --rm -v "$(pwd)/$dir:/work" -w /work "$IMG" bash -c "$*"
}

echo "== Cleaning previous generated artifacts =="
for d in domain-ns tld-ns root-ns; do
  rm -rf "$d/keys" "$d/build" "$d"/*.signed
  mkdir -p "$d/keys" "$d/build"
done
rm -f resolver/trust-anchor.conf

# ---- 1. domain-ns signs example.com (leaf zone) ----------------------------
echo "== [1/4] Signing example.com (domain-ns) =="
run_in domain-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys example.com. >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys example.com. >/dev/null
  cp db.example.com build/db.example.com
  cd build
  dnssec-signzone -S -N keep -K ../keys -o example.com. \
      -f db.example.com.signed db.example.com >/dev/null
"
cp domain-ns/build/db.example.com.signed domain-ns/db.example.com.signed

# ---- 2. tld-ns: chain in example.com's DS, then sign com -------------------
echo "== [2/4] Chaining example.com's DS into com, signing com (tld-ns) =="
cp tld-ns/db.com tld-ns/build/db.com
{
  echo ""
  echo "; DS record for the example.com delegation (chains to its signed zone)"
  cat domain-ns/build/dsset-example.com.
} >> tld-ns/build/db.com
run_in tld-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys com. >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys com. >/dev/null
  cd build
  dnssec-signzone -S -N keep -K ../keys -o com. \
      -f db.com.signed db.com >/dev/null
"
cp tld-ns/build/db.com.signed tld-ns/db.com.signed

# ---- 3. root-ns: chain in com's DS, then sign the root zone ----------------
echo "== [3/4] Chaining com's DS into the root zone, signing . (root-ns) =="
cp root-ns/db.root root-ns/build/db.root
{
  echo ""
  echo "; DS record for the com delegation (chains to its signed zone)"
  cat tld-ns/build/dsset-com.
} >> root-ns/build/db.root
run_in root-ns "
  set -e
  dnssec-keygen -a $ALG -n ZONE -f KSK -K keys . >/dev/null
  dnssec-keygen -a $ALG -n ZONE         -K keys . >/dev/null
  cd build
  dnssec-signzone -S -N keep -K ../keys -o . \
      -f db.root.signed db.root >/dev/null
  mv 'dsset-.' dsset-root
"
cp root-ns/build/db.root.signed root-ns/db.root.signed

# ---- 4. derive the resolver's trust anchor from root-ns's own DS -----------
echo "== [4/4] Writing resolver trust anchor from root-ns's DS =="
# A dsset line is "<name> [TTL] IN DS <keytag> <algo> <digest-type> <digest>"
# -- locate the literal "DS" token instead of assuming a fixed column, since
# whether a TTL field is present shifts everything after it by one.
DS_LINE=$(grep -E "IN[[:space:]]+DS" root-ns/build/dsset-root | head -1)
read -r KEYTAG DSALGO DIGTYPE DIGEST <<<"$(echo "$DS_LINE" | awk '
  { for (i=1;i<=NF;i++) if ($i=="DS") {
      d=""; for (j=i+4;j<=NF;j++) d=d $j
      print $(i+1), $(i+2), $(i+3), d
      exit
    } }')"

cat > resolver/trust-anchor.conf <<EOF
// Generated by sign-zones.sh -- DO NOT COMMIT (regenerated every run, see
// .gitignore). This is the DS of this run's freshly-generated root zone
// KSK, installed as the resolver's sole trust anchor for the "." zone.
trust-anchors {
    "." static-ds $KEYTAG $DSALGO $DIGTYPE "$DIGEST";
};
EOF

echo
echo "Done."
echo "  domain-ns/db.example.com.signed"
echo "  tld-ns/db.com.signed"
echo "  root-ns/db.root.signed"
echo "  resolver/trust-anchor.conf  ->  $(cat resolver/trust-anchor.conf | tail -2 | head -1)"
echo
echo "Now run: docker compose up -d --build"
